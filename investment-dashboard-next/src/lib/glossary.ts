/** Commentary.terms から、辞書に存在する定義だけを順序保持で取り出す */
export function resolveTerms(terms: string[] | undefined): { term: string; note: string }[] {
  if (!terms) return [];
  const seen = new Set<string>();
  const out: { term: string; note: string }[] = [];
  for (const t of terms) {
    if (seen.has(t)) continue;
    const note = GLOSSARY[t];
    if (note) {
      out.push({ term: t, note });
      seen.add(t);
    }
  }
  return out;
}
